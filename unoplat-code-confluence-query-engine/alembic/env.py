# ruff: noqa: INP001
"""Explicit, async PostgreSQL migrations for the shared application database."""

import os
import asyncio
from collections.abc import Collection, Mapping
from logging.config import fileConfig
import re
import time
from typing import Final

from alembic import context
from alembic.runtime.environment import NameFilterParentNames, NameFilterType
from alembic.runtime.migration import MigrationContext, MigrationInfo
from sqlalchemy import Connection, pool
from sqlalchemy.engine import URL, make_url
from sqlalchemy.ext.asyncio import create_async_engine

from unoplat_code_confluence_query_engine.db.postgres.migration_metadata import (
    application_metadata,
)

config = context.config
if config.config_file_name is not None:
    fileConfig(config.config_file_name)

target_metadata = application_metadata()

# Serializes every migration job against one database. Transaction scope means
# commit, rollback or a lost connection always releases it.
MIGRATION_ADVISORY_LOCK_KEY: Final[int] = 7306492816275
MIGRATION_LOCK_WAIT_SECONDS: Final[int] = 60
MIGRATION_LOCK_POLL_SECONDS: Final[float] = 1.0
MIGRATION_DDL_LOCK_TIMEOUT: Final[str] = "5s"
TEMPORAL_DATABASES: Final[frozenset[str]] = frozenset(
    {"temporal", "temporal_visibility"}
)
# Operator attestations, passed as -x <name>=true. Revisions check the settings in
# SQL, so online runs and generated offline SQL enforce the same gates.
ATTESTATION_SETTINGS: Final[Mapping[str, str]] = {
    "drained": "unoplat.git_artifacts_drained",
    "discard_legacy_artifacts": "unoplat.git_artifacts_discard_legacy",
}


def migration_url() -> URL:
    """Require an explicit database target, without logging credentials."""
    value = os.environ.get("ALEMBIC_DATABASE_URL")
    if not value:
        raise RuntimeError("Set ALEMBIC_DATABASE_URL explicitly before migrating")
    url = make_url(value)
    if url.get_backend_name() != "postgresql" or not url.database:
        raise RuntimeError("Migrations require an explicit PostgreSQL database")
    if url.database in TEMPORAL_DATABASES:
        raise RuntimeError("Application migrations must not target Temporal databases")
    return url.set(drivername="postgresql+asyncpg")


def migration_schema() -> str:
    """Accept a simple, explicit PostgreSQL application schema identifier."""
    schema = os.environ.get("ALEMBIC_SCHEMA", "public")
    if re.fullmatch(r"[a-z_][a-z0-9_]*", schema) is None:
        raise RuntimeError("ALEMBIC_SCHEMA must be a lowercase SQL identifier")
    return schema


def include_name(
    name: str | None, type_: NameFilterType, parent_names: NameFilterParentNames
) -> bool:
    """Never propose autogenerated drops for unrelated database tables."""
    if type_ == "table":
        return name in target_metadata.tables
    return True


def verify_stamp_attestation(
    ctx: MigrationContext,
    step: MigrationInfo,
    heads: Collection[object],
    run_args: Mapping[str, object],
) -> None:
    """Reject unacknowledged stamps; this flag does not perform a schema audit."""
    if (
        step.is_stamp
        and context.get_x_argument(as_dictionary=True).get("baseline_verified")
        != "true"
    ):
        raise RuntimeError(
            "Stamping requires a recorded schema/data audit and -x baseline_verified=true; "
            "never use stamp to hide a schema mismatch"
        )


def attestation_statements() -> list[str]:
    """Return a transaction-local setting for each attestation set to true."""
    arguments = context.get_x_argument(as_dictionary=True)
    return [
        f"SET LOCAL {setting} = 'true'"
        for name, setting in ATTESTATION_SETTINGS.items()
        if arguments.get(name) == "true"
    ]


def acquire_migration_lock(connection: Connection) -> None:
    """Wait a bounded time for the transaction-scoped migration lock.

    Alembic reads and creates its version table in run_migrations(), so callers
    take this first. Each later READ COMMITTED statement then sees the previous
    job's committed revision instead of racing a concurrent fresh bootstrap.
    """
    deadline = time.monotonic() + MIGRATION_LOCK_WAIT_SECONDS
    while not connection.exec_driver_sql(
        f"SELECT pg_try_advisory_xact_lock({MIGRATION_ADVISORY_LOCK_KEY})"
    ).scalar():
        if time.monotonic() >= deadline:
            raise RuntimeError(
                "Another migration job still holds the application migration lock; "
                "retry after it finishes"
            )
        time.sleep(MIGRATION_LOCK_POLL_SECONDS)
    connection.exec_driver_sql(
        f"SET LOCAL lock_timeout = '{MIGRATION_DDL_LOCK_TIMEOUT}'"
    )


def do_run_migrations(connection: Connection) -> None:
    """Run the revision chain in one transaction on an isolated connection."""
    schema = migration_schema()
    with connection.begin():
        acquire_migration_lock(connection)
        # Identifier validation above makes interpolation safe. SET LOCAL cannot
        # leak the schema selection back to another connection or application.
        connection.exec_driver_sql(f'SET LOCAL search_path TO "{schema}"')
        actual_schema = connection.exec_driver_sql("SELECT current_schema()").scalar()
        if actual_schema != schema:
            raise RuntimeError("ALEMBIC_SCHEMA does not exist or is inaccessible")
        connection.dialect.default_schema_name = schema
        for statement in attestation_statements():
            connection.exec_driver_sql(statement)
        context.configure(
            connection=connection,
            target_metadata=target_metadata,
            version_table_schema=schema,
            include_name=include_name,
            compare_type=True,
            compare_server_default=True,
            on_version_apply=verify_stamp_attestation,
        )
        context.run_migrations()


async def run_async_migrations() -> None:
    """Dispose the migration engine even when a migration fails."""
    engine = create_async_engine(migration_url(), poolclass=pool.NullPool)
    try:
        async with engine.connect() as connection:
            await connection.run_sync(do_run_migrations)
    finally:
        await engine.dispose()


def run_migrations_offline() -> None:
    """Emit reviewable SQL; operational gates remain in the generated SQL."""
    schema = migration_schema()
    context.configure(
        url=migration_url(),
        target_metadata=target_metadata,
        literal_binds=True,
        dialect_opts={"paramstyle": "named"},
        version_table_schema=schema,
        on_version_apply=verify_stamp_attestation,
    )
    with context.begin_transaction():
        # Generated SQL cannot poll, so its bounded wait uses lock_timeout.
        context.execute(f"SET LOCAL lock_timeout = '{MIGRATION_LOCK_WAIT_SECONDS}s'")
        context.execute(f"SELECT pg_advisory_xact_lock({MIGRATION_ADVISORY_LOCK_KEY})")
        context.execute(f"SET LOCAL lock_timeout = '{MIGRATION_DDL_LOCK_TIMEOUT}'")
        context.execute(f'SET LOCAL search_path TO "{schema}"')
        for statement in attestation_statements():
            context.execute(statement)
        context.run_migrations()


if context.is_offline_mode():
    run_migrations_offline()
else:
    supplied_connection = config.attributes.get("connection")
    if supplied_connection is not None:
        do_run_migrations(supplied_connection)
    else:
        asyncio.run(run_async_migrations())
